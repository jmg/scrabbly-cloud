    for es_slug, data in EN.items():
        # Tag the Spanish original with the shared translation group.
        Post.objects.filter(slug=es_slug).update(translation_group=es_slug)
        Post.objects.get_or_create(
            slug=data["slug"],
            defaults={**data, "language": "en", "translation_group": es_slug},
        )


